/// Maps macOS virtual key codes (Carbon `kVK_*`, as in `NSEvent.keyCode`) to HID usages.
/// Key codes are physical positions, so the TV interprets them with its own layout (US by default).
public enum MacKeyCodeMap {
    public static func stroke(forKeyCode keyCode: UInt16, modifiers: HIDModifiers) -> HIDKeyStroke? {
        usages[keyCode].map { HIDKeyStroke(usage: $0, modifiers: modifiers) }
    }

    private static let usages: [UInt16: UInt8] = [
        // Letters
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, 0x05: 0x0A, 0x04: 0x0B,
        0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, 0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13,
        0x0C: 0x14, 0x0F: 0x15, 0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B,
        0x10: 0x1C, 0x06: 0x1D,
        // Digits 1–9, 0
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22, 0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25,
        0x19: 0x26, 0x1D: 0x27,
        // Return, Escape, Delete (backspace), Tab, Space
        0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,
        // - = [ ] \ ; ' ` , . /
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31, 0x29: 0x33, 0x27: 0x34, 0x32: 0x35,
        0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38,
        // Home, Page Up, Forward Delete, End, Page Down, arrows (right, left, down, up), keypad Enter
        0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x77: 0x4D, 0x79: 0x4E,
        0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52, 0x4C: 0x58,
    ]
}
